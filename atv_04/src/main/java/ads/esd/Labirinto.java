    public boolean verificarPosicao() {
        if (mapa[linhaAtual +1][colunaAtual] == 'T' || mapa[linhaAtual][colunaAtual + 1] == 'T'){
            // Econtrado
            mapa[linhaAtual][colunaAtual] = '+';
            return true;
        }

        if(pilha.isEmpty()){
            pilha.push(new Coordenada(linhaInicial, colunaInicial));
        }else{
            mapa[linhaAtual][colunaAtual] = '+';
        }


        if (mapa[linhaAtual + 1][colunaAtual] == ' ') {
            // Pra baixo
            linhaAtual += 1;
            pilha.push(new Coordenada(linhaAtual, colunaAtual));
            return false;
        }

        if (mapa[linhaAtual][colunaAtual + 1] == ' ') {
            // Pra direita
            colunaAtual += 1;
            pilha.push(new Coordenada(linhaAtual, colunaAtual));
            return false;
        }

        if (mapa[linhaAtual - 1][colunaAtual] == ' ') {
            // Pra cima
            linhaAtual -= 1;
            pilha.push(new Coordenada(linhaAtual, colunaAtual));
            return false;
        }

        if (mapa[linhaAtual][colunaAtual - 1] == ' ') {
            // Pra esquerda
            colunaAtual -= 1;
            pilha.push(new Coordenada(linhaAtual, colunaAtual));
            return false;
        }

        // Beco sem saída
        Coordenada coordenadaAtual = pilha.pop();
        linhaAtual = coordenadaAtual.getX();
        colunaAtual = coordenadaAtual.getY();
        return false;
    }
